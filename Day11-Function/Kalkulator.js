function tambah (a,b){
    return a+b;
}
function kurang(a, b){
    return a-b;
}
function bagi(a, b){
    return a/b;
}
function kali(a,b){
    return a * b;
}

let hasiltambah = tambah(20,10);
let hasilkurang= kurang(20,10);
let hasilbagi = bagi(20,10);
let hasilkali = kali(20,10);

console.log("Hasil Tambah   :", hasiltambah);
console.log("Hasil Kurang   :", hasilkurang);
console.log("Hasil bagi :", hasilbagi);
console.log("Hasil Kali :", hasilkali);